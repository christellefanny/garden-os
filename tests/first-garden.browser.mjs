// First-time guest flow on isolated local data. No real accounts or production writes.
import { chromium } from 'playwright';
import { isolateBrowserContext } from './helpers/isolated-browser.mjs';
import { spawn } from 'node:child_process';
import { mkdirSync, readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
const port = 3052, fixturePort = 54331;
const fixtureSource = readFileSync(new URL('./fixtures/supabase.mjs', import.meta.url), 'utf8').replace('server.listen(54321,', `server.listen(${fixturePort},`);
const fixture = spawn(process.execPath, ['--input-type=module', '-e', fixtureSource], { stdio: 'ignore' });
const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'dev', '--hostname', '127.0.0.1', '--port', String(port)], { env: { ...process.env, NEXT_PUBLIC_SUPABASE_URL: `http://127.0.0.1:${fixturePort}`, NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: 'garden-os-local-preview' }, stdio: 'ignore' });
const out = process.env.PREVIEW_DIR || '/tmp/first-garden-preview';
mkdirSync(out, { recursive: true });
let browser;
try {
  let ready = false;
  for (let i=0;i<160;i++) { try { if ((await fetch(`http://127.0.0.1:${port}`)).ok) { ready = true; break; } } catch {} await new Promise(r=>setTimeout(r,250)); }
  assert.ok(ready, 'The isolated local app must be ready before browser checks start.');
  browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || '/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
  const desktopContext = await browser.newContext({ viewport:{width:1440,height:1000} });
  await isolateBrowserContext(desktopContext);
  const page = await desktopContext.newPage();
  const errors=[], cloudWrites=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()!=='GET' && /rest\/v1|api\/state/.test(r.url()))cloudWrites.push(r.url());});
  await page.goto(`http://127.0.0.1:${port}`);
  await page.getByRole('button',{name:'Try it as a guest',exact:true}).click();
  await page.getByRole('button',{name:'Continue as guest',exact:true}).click();
  const steps = page.getByRole('region',{name:'Your first garden steps'});
  await steps.waitFor();
  await page.screenshot({path:`${out}/first-garden-desktop.png`});
  await steps.screenshot({path:`${out}/first-garden-steps-desktop.png`});
  await steps.getByRole('button',{name:'Start my garden →',exact:true}).click();
  await page.getByRole('dialog',{name:'Create your garden'}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.goBack();
  assert.ok(!new URL(page.url()).searchParams.has('garden'));
  await steps.getByRole('button',{name:'Start my garden →',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('navigation',{name:'Garden Atelier navigation'}).getByRole('button',{name:'Calendar',exact:true}).click();
  await page.getByRole('heading',{name:'Make this calendar yours'}).waitFor();
  assert.equal(await page.getByText(/Add plants in Plant Vault first/).count(),0);
  await page.screenshot({path:`${out}/calendar-empty-desktop.png`});
  await page.getByRole('button',{name:'Add reminder',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Create your first garden',exact:true}).click();
  await page.getByRole('dialog',{name:'Create your garden'}).waitFor();
  await page.getByLabel('Garden Name',{exact:true}).fill('My first kitchen garden');
  await page.getByLabel('Hardiness Zone (optional)',{exact:true}).fill('6a');
  await page.getByRole('button',{name:'Save Garden',exact:true}).click();
  await steps.getByText('Zone 6a',{exact:true}).waitFor();
  await steps.getByRole('button',{name:'Add a bed or container →',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Kitchen herb bed');
  await page.getByLabel('Length (feet)',{exact:true}).fill('4');
  await page.getByLabel('Width (feet)',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Save Growing Space',exact:true}).click();
  await page.getByRole('heading',{name:'Add Plant',exact:true}).waitFor();
  await page.getByLabel('Plant name',{exact:true}).fill('Basil');
  await page.getByLabel('Spacing (inches)',{exact:true}).fill('12');
  await page.getByRole('button',{name:'Save Plant',exact:true}).click();
  await page.getByText('Plant saved.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await steps.getByRole('button',{name:'Add your first task',exact:true}).click();
  await page.getByLabel('Task',{exact:true}).fill('Check basil soil before watering');
  await page.getByRole('button',{name:'Save task',exact:true}).click();
  await page.getByRole('heading',{name:'Calendar',exact:true}).waitFor();
  await page.getByText('Check basil soil before watering',{exact:true}).first().waitFor();
  await page.reload();
  await page.getByText('Check basil soil before watering',{exact:true}).first().waitFor();
  await page.getByRole('navigation',{name:'Garden Atelier navigation'}).getByRole('button',{name:'Home',exact:true}).click();
  assert.equal(await steps.count(),0,'completed guidance disappears');
  const data = await page.evaluate(()=>({guest:JSON.parse(localStorage.getItem('garden-os-guest-data')),plants:JSON.parse(localStorage.getItem('garden-os-plant-vault-guest')),calendar:JSON.parse(localStorage.getItem('garden-os-calendar-guest'))}));
  assert.equal(data.guest.gardens.length,1);assert.equal(data.guest.spaces.length,1);assert.equal(data.plants.length,1);assert.equal(data.calendar.reminders.length,1);
  assert.deepEqual(cloudWrites,[]);assert.deepEqual(errors,[]);
  console.log('PASS guest zone → garden → bed → first plant → first calendar task, reload, no duplicates or cloud writes.');
  const mobileContext = await browser.newContext({viewport:{width:390,height:844}});
  await isolateBrowserContext(mobileContext);
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror',e=>errors.push(e.message));
  mobile.on('request',r=>{if(r.method()!=='GET' && /rest\/v1|api\/state/.test(r.url()))cloudWrites.push(r.url());});
  await mobile.goto(`http://127.0.0.1:${port}`);
  await mobile.getByRole('button',{name:'Try it as a guest',exact:true}).click();
  await mobile.getByRole('button',{name:'Continue as guest',exact:true}).click();
  await mobile.screenshot({path:`${out}/first-garden-mobile.png`});
  await mobile.getByRole('region',{name:'Your first garden steps'}).screenshot({path:`${out}/first-garden-steps-mobile.png`});
  await mobile.getByRole('region',{name:'Your first garden steps'}).getByRole('button',{name:'Start my garden →',exact:true}).click();
  const axe=await new AxeBuilder({page:mobile}).include('dialog').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(axe.violations.map(v=>v.id),[]);
  await mobile.screenshot({path:`${out}/create-garden-mobile.png`});
  await mobile.getByLabel('Garden Name',{exact:true}).fill('One small pot');
  await mobile.getByRole('button',{name:'Save Garden',exact:true}).click();
  await mobile.getByRole('region',{name:'Your first garden steps'}).getByRole('button',{name:'Add a bed or container →',exact:true}).waitFor();
  await mobile.getByRole('navigation',{name:'Garden Atelier navigation'}).getByRole('button',{name:'Calendar',exact:true}).click();
  await mobile.getByRole('button',{name:'Add your first task',exact:true}).click();
  await mobile.keyboard.press('Escape');
  assert.equal(await mobile.getByRole('dialog').count(),0);
  await mobile.getByRole('button',{name:'Add your first task',exact:true}).click();
  await mobile.getByLabel('Task',{exact:true}).fill('Choose my first herb');
  await mobile.getByRole('button',{name:'Save task',exact:true}).click();
  await mobile.getByText('Choose my first herb',{exact:true}).first().waitFor();
  await mobile.setViewportSize({width:320,height:740});
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await mobile.setViewportSize({width:390,height:844});
  await mobile.screenshot({path:`${out}/calendar-empty-mobile.png`});
  assert.deepEqual(cloudWrites,[]);assert.deepEqual(errors,[]);
  console.log('PASS optional zone, task without a plant, mobile 320/390, accessible garden dialog, Cancel/Escape/Back and interrupted task.');
} finally { await browser?.close();server.kill();fixture.kill(); }
