function key(name: string, variety = "") {
  return `${name.trim().toLowerCase().replace(/[’']/g, "").replace(/\s+/g, " ")}|${variety.trim().toLowerCase().replace(/[’']/g, "").replace(/\s+/g, " ")}`;
}
const subjects = new Map(vaultBotanicalSubjects.map((plant, index) => [key(plant.name, plant.variety), index]));

/** Exact cultivar matches first; never borrow a different named cultivar's colors. */
export function getVaultBotanicalArt(name: string, variety = "") {
  const index = subjects.get(key(name, variety));
  if (index === undefined) return null;
  const plate = Math.floor(index / 16) + 1;
  const tile = index % 16;
  const columns = plate === 8 ? 2 : 4;
  return {
    src: `/plant-vault/illustrated-collection-${plate}.webp`,
    column: tile % columns,
    row: Math.floor(tile / columns),
    columns,
    illustration: true,
    caption: variety ? "Botanical illustration · variety reference" : "Botanical illustration · representative plant form",
  };
}
